const SUPABASE_HOST_SUFFIXES = [".supabase.com", ".supabase.co"];

/**
 * node-postgres only negotiates TLS when it's configured to, and the Prisma pg
 * adapter passes no TLS options, so without this a URL like
 * `...pooler.supabase.com:6543/postgres?pgbouncer=true` connects in plaintext.
 *
 * Supabase serves certificates signed by its own root CA, so we verify
 * against that CA (hostname included) instead of the system trust store.
 * An explicit `sslmode` in the URL still wins, since pg applies connection
 * string params over the config object.
 */
export const getDatabaseSslConfig = (
  connectionString: string,
): ConnectionOptions | undefined => {
  const { hostname } = new URL(connectionString);

  if (SUPABASE_HOST_SUFFIXES.some((suffix) => hostname.endsWith(suffix))) {
    return { ca: SUPABASE_ROOT_2021_CA };
  }

  return undefined;
};
